import { describe, expect, it } from "vitest";

import {
	applyEmailBranding,
	DEFAULT_EMAIL_BRANDING,
	emailButtonSizeStyle,
	resolveEmailBranding,
} from "../src/email-branding.js";

describe("email branding", () => {
	it("uses the configured logo, site name, colors, and font", () => {
		const branding = resolveEmailBranding({
			title: "Acme",
			logo: { alt: "Acme logo", url: "/media/acme.svg" },
			theme: {
				colors: { primary: "#336699", background: "#eeeeee", onPrimary: "#ffffff" },
				fonts: { body: "Arial, sans-serif" },
			},
		});

		expect(branding).toMatchObject({
			logoUrl: "/media/acme.svg",
			logoAlt: "Acme logo",
			siteName: "Acme",
			primary: "#336699",
			background: "#eeeeee",
			font: "Arial, sans-serif",
		});
	});

	it("uses the black primary fallback and text fallback when branding is missing", () => {
		const branding = resolveEmailBranding();

		expect(branding.primary).toBe(DEFAULT_EMAIL_BRANDING.primary);
		expect(branding.primary).toBe("#000000");
		expect(branding.logoUrl).toBeUndefined();
		expect(branding.siteName).toBe("");
	});

	it("adds one branded header and replaces it instead of duplicating it", () => {
		const branding = resolveEmailBranding({
			title: "Acme",
			logo: { url: "/media/acme.svg" },
			theme: { colors: { primary: "#000000", background: "#eeeeee" } },
		});
		const html = "<html><body><main>Message</main></body></html>";

		const first = applyEmailBranding(html, branding);
		const second = applyEmailBranding(first, branding);

		expect(first).not.toContain('data-emdash-email-branding="true"');
		expect(first).not.toContain("/media/acme.svg");
		expect(first).toContain("background-color:#eeeeee");
		expect(second).toBe(first);
	});

	it("applies the theme colors to existing email buttons", () => {
		const branding = resolveEmailBranding({
			theme: { colors: { primary: "#336699", onPrimary: "#ffffff" } },
		});
		const html =
			'<html><body><a class="node-button" style="background-color:#111827;color:#000;padding:12px;">Continue</a></body></html>';

		const branded = applyEmailBranding(html, branding);

		expect(branded).toContain("background-color:#336699;");
		expect(branded).toContain("color:#ffffff;");
		expect(branded).toContain("padding:12px;");
		expect(branded).not.toContain("background-color:#111827");
		expect(branded).not.toContain("color:#000");
	});

	it("compacts legacy footer spacing when an existing template is opened", () => {
		const branding = resolveEmailBranding();
		const html =
			'<html><body><section style="--emdash-email-footer:1;margin:16px auto 0;padding:28px 24px 20px;"><p style="text-align:center;font-size:13px;">Copyright</p><p style="text-align:center;font-size:12px;margin-top:16px;">Unsubscribe</p></section></body></html>';

		const branded = applyEmailBranding(html, branding);

		expect(branded).toContain("margin:32px auto 0");
		expect(branded).toContain("padding:10px 24px 8px");
		expect(branded).toContain("min-height:0;height:auto;");
		expect(branded).toContain("font-size:13px;margin:0;");
		expect(branded).toContain("font-size:12px;margin:4px 0 0;");
	});

	it("compacts footer tables generated by the email editor", () => {
		const branding = resolveEmailBranding();
		const html =
			'<html><body><table style="--emdash-email-footer:1;"><tbody><tr><td style="padding:16px 24px 12px;"><p style="margin:0;padding:0;padding-top:0.5em;padding-bottom:0.5em;">Copyright</p><p style="margin:8px 0 0;padding:0;padding-top:0.5em;padding-bottom:0.5em;">Unsubscribe</p></td></tr></tbody></table></body></html>';

		const branded = applyEmailBranding(html, branding);

		expect(branded).toContain("margin:0;padding:0;");
		expect(branded).toContain("margin:4px 0 0;padding:0;");
		expect(branded).not.toContain("padding-top:0.5em");
		expect(branded).not.toContain("padding-bottom:0.5em");
	});

	it("provides small, medium, and large button sizes with medium as the default", () => {
		expect(emailButtonSizeStyle("sm")).toBe("padding:8px 16px;font-size:14px;");
		expect(emailButtonSizeStyle()).toBe("padding:12px 24px;font-size:16px;");
		expect(emailButtonSizeStyle("large")).toBe("padding:16px 32px;font-size:18px;");
	});
});
