export function isTransferErrorCode(code: string | undefined): code is TransferErrorCode {
	return code !== undefined && Object.hasOwn(TRANSFER_ERROR_STATUS, code);
}

export function transferErrorStatus(code: string | undefined): number | undefined {
	return isTransferErrorCode(code) ? TRANSFER_ERROR_STATUS[code] : undefined;
}

/**
 * JSON-safe, bounded detail attached to a transfer error. Never put record
 * contents, credentials, or storage keys here: details reach API clients and
 * operation rows.
 */
export type TransferErrorDetail = Readonly<Record<string, string | number | boolean | null>>;

export const transferErrorDetailSchema = z.record(
	z.string(),
	z.union([z.string(), z.number(), z.boolean(), z.null()]),
);

export class TransferError extends Error {
	readonly code: TransferErrorCode;
	readonly status: number;
	readonly detail: TransferErrorDetail | undefined;

	constructor(
		code: TransferErrorCode,
		message: string,
		options: { detail?: TransferErrorDetail; cause?: unknown } = {},
	) {
		super(message, options.cause === undefined ? undefined : { cause: options.cause });
		this.name = "TransferError";
		this.code = code;
		this.status = TRANSFER_ERROR_STATUS[code];
		this.detail = options.detail;
	}
}

export function isTransferError(error: unknown): error is TransferError {
	return error instanceof TransferError;
}
