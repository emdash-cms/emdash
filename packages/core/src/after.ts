/**
 * Defer work past the HTTP response.
 *
 * Use for bookkeeping that doesn't need to complete before the client
 * gets bytes — writes that record state, maintenance queries, cache
 * refreshes. `after()` hands the promise to a host lifetime extender. A
 * per-request `waitUntil` on `locals` (Netlify's `locals.netlify.context`, or
 * `locals.waitUntil` set by the site) takes precedence over Vercel's request
 * context, then `virtual:emdash/wait-until` (Cloudflare), with a workerd
 * runtime probe when the adapter did not provide a binding.
 *
 * With none of these the task runs without one, which is only safe when the
 * process outlives the response (`@astrojs/node`). Import failures are
 * caught so tools that load core in plain Node (`astro check`, Vitest, etc.)
 * work without either host module.
 */

import { trackDeferredTask } from "./deferred-tasks.js";
import { getRequestContext } from "./request-context.js";

export type WaitUntilFn = (promise: Promise<unknown>) => void;

interface HostLifetime {
	waitUntil: WaitUntilFn | null;
	longLivedProcess: boolean;
}

// Kicked off once at module load; subsequent calls see the cached result
// without re-importing.
const hostReady: Promise<HostLifetime> = (async () => {
	let longLivedProcess = false;
	try {
		// @ts-ignore - virtual module, generated by the Astro integration
		const mod = (await import("virtual:emdash/wait-until")) as {
			waitUntil?: WaitUntilFn;
			longLivedProcess?: boolean;
		};
		if (mod.waitUntil) return { waitUntil: mod.waitUntil, longLivedProcess: false };
		longLivedProcess = mod.longLivedProcess === true;
	} catch {
		// Tooling may load core without the integration's virtual modules.
	}

	try {
		// Injected or vendored adapters may not be known at config:setup.
		// @ts-ignore - optional workerd built-in; unavailable on Node
		// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- workerd's binding has no Node declarations
		const mod = (await import("cloudflare:workers")) as { waitUntil?: WaitUntilFn };
		return { waitUntil: mod.waitUntil ?? null, longLivedProcess };
	} catch {
		return { waitUntil: null, longLivedProcess };
	}
})();
// Surface rejections without making the module-load fail.
hostReady.catch(() => {});

const VERCEL_REQUEST_CONTEXT = Symbol.for("@vercel/request-context");

interface VercelRequestContext {
	get?: () => { waitUntil?: WaitUntilFn } | undefined;
}

function requestWaitUntil(): WaitUntilFn | undefined {
	const fromRequest = getRequestContext()?.hostWaitUntil?.();
	if (fromRequest) return fromRequest;

	// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- global published by the Vercel runtime
	const vercel = (globalThis as Record<symbol, unknown>)[VERCEL_REQUEST_CONTEXT] as
		| VercelRequestContext
		| undefined;
	const context = vercel?.get?.();
	const waitUntil = context?.waitUntil;
	return typeof waitUntil === "function" ? waitUntil.bind(context) : undefined;
}

/**
 * Whether work passed to `after()` will finish after the response: the host
 * provides a lifetime extender, or the process is long-lived.
 */
export async function canRunAfterResponse(): Promise<boolean> {
	if (requestWaitUntil()) return true;
	const host = await hostReady;
	return host.waitUntil !== null || host.longLivedProcess;
}

/**
 * Schedule `fn` to run without blocking the response.
 *
 * Errors are caught and logged — a deferred task should never surface
 * as an unhandled rejection because the response is long gone. Callers
 * that care about errors should handle them inside `fn`.
 */
export function after(fn: () => void | Promise<void>): void {
	const task = Promise.resolve()
		.then(fn)
		.catch((error) => {
			console.error("[emdash] deferred task failed:", error);
		});
	const requestTask = getRequestContext()?.deferredTasks?.track(task) ?? task;
	const promise = trackDeferredTask(requestTask);

	const fromRequest = requestWaitUntil();
	if (fromRequest) {
		fromRequest(promise);
		return;
	}

	void hostReady.then(({ waitUntil }) => {
		if (waitUntil) waitUntil(promise);
		return null;
	});
}
